"""Fill the two "original files" folders from Wikimedia Commons, which keeps
uploaded files byte for byte (metadata intact).

  real:  random Commons photos with camera details, taken before 2021
         (before AI images were hard to spot, so "real" is a safe label)
  ai:    files from Commons' "Images generated by <tool>" categories, a few per tool

Each saved file gets a row in collect/sources_wikimedia.csv with its Commons page.

    .venv/bin/python collect/wikimedia.py real 60
    .venv/bin/python collect/wikimedia.py ai 60
"""

import csv
import hashlib
import random
import re
import sys
import time
from pathlib import Path

import requests

HERE = Path(__file__).resolve().parent.parent
IMAGES = HERE / "images"
SOURCES = HERE / "collect" / "sources_wikimedia.csv"
API = "https://commons.wikimedia.org/w/api.php"
S = requests.Session()
# Wikimedia asks scripts to include contact details, and throttles ones that don't.
# Put your own contact (an email or URL) in collect/contact.txt; it isn't included in the repo.
_contact_file = HERE / "collect" / "contact.txt"
_contact = _contact_file.read_text().strip() if _contact_file.exists() else ""
S.headers["User-Agent"] = f"provenance-test/0.1 (research script{'; ' + _contact if _contact else ''}) python-requests"

# Current tools first. Old ones (Deep Dream, VQGAN, Craiyon) are left out: nobody mistakes them for photos.
AI_CATEGORIES = [
    "Images generated by ChatGPT", "GPT Image", "Images generated by Gemini", "Images generated by Nano Banana",
    "Images generated by Imagen", "Images generated by Midjourney", "Images generated by Flux (text-to-image model)",
    "Images generated by Adobe Firefly AI", "Images generated by Meta AI", "Images generated by Grok",
    "Images generated by Ideogram", "Images generated by Seedream", "Images generated by Qwen",
    "Images generated by Reve Image", "Images generated by Recraft", "Images generated by Stable Diffusion",
    "Images generated by DALL-E", "Images generated by Image Creator by Microsoft Bing",
]
IMAGE_MIMES = {"image/jpeg", "image/png", "image/webp"}
MAX_BYTES = 15_000_000


def get(url, **kw):
    """GET with backoff: Wikimedia answers 429 when requests come too fast."""
    for attempt in range(8):
        r = S.get(url, timeout=60, **kw)
        if r.status_code != 429:
            return r
        wait = int(r.headers.get("Retry-After", 0) or 0) or 10 * (attempt + 1)
        print(f"  (rate limited, waiting {wait} s)")
        time.sleep(wait)
    return r


def download(url, limit_s=90):
    """Fetch a file, giving up if it takes longer than limit_s in total (a stalled
    connection can otherwise trickle forever without tripping the normal timeout)."""
    start = time.time()
    try:
        r = get(url, stream=True)
        if r.status_code != 200:
            return None
        chunks = []
        for chunk in r.iter_content(65536):
            chunks.append(chunk)
            if time.time() - start > limit_s:
                print(f"  (gave up on a slow download after {limit_s} s)")
                r.close()
                return None
        return b"".join(chunks)
    except requests.RequestException as e:
        print(f"  (download failed: {type(e).__name__})")
        return None


def api(**params):
    params.update(format="json", formatversion=2)
    r = get(API, params=params)
    r.raise_for_status()
    time.sleep(1)
    return r.json()


def meta_value(ii, key):
    for m in ii.get("metadata") or []:
        if m.get("name") == key:
            return m.get("value")
    return None


def slug(title):
    stem = Path(title.replace("File:", "")).stem
    s = re.sub(r"[^A-Za-z0-9]+", "-", stem).strip("-")[:50]
    # Titles in non-Latin scripts would otherwise come out empty and overwrite each other
    return f"{s}-{hashlib.md5(title.encode()).hexdigest()[:6]}" if s else hashlib.md5(title.encode()).hexdigest()[:12]


def already_have():
    if not SOURCES.exists():
        return set()
    return {r["origin_url"] for r in csv.DictReader(SOURCES.open())}


def save(title, ii, truth, origin, notes, seen):
    page = "https://commons.wikimedia.org/wiki/" + title.replace(" ", "_")
    if page in seen:
        return False
    ext = {"image/jpeg": ".jpg", "image/png": ".png", "image/webp": ".webp"}[ii["mime"]]
    name = f"wm_{slug(title)}{ext}"
    rel = f"{truth}/direct/{name}"
    data = download(ii["url"])
    if data is None:
        return False
    (IMAGES / rel).write_bytes(data)
    new = not SOURCES.exists()
    with SOURCES.open("a", newline="") as fh:
        w = csv.writer(fh)
        if new:
            w.writerow(["file", "truth", "source", "origin", "origin_url", "notes"])
        w.writerow([rel, truth, "direct", origin, page, notes])
    seen.add(page)
    print(f"  {rel}  ({notes})", flush=True)
    time.sleep(2)
    return True


def collect_real(n):
    seen = already_have()
    got = sum(1 for r in csv.DictReader(SOURCES.open()) if r["truth"] == "real") if SOURCES.exists() else 0
    batches = 0
    while got < n:
        batches += 1
        if batches % 10 == 0:
            print(f"  ({batches} batches searched, {got} real photos so far)", flush=True)
        # requestid makes each URL unique; without it a cache returns the same "random" batch every time
        d = api(action="query", generator="random", grnnamespace=6, grnlimit=50,
                prop="imageinfo", iiprop="url|size|mime|metadata", requestid=random.getrandbits(48))
        for p in d["query"]["pages"]:
            ii = (p.get("imageinfo") or [{}])[0]
            if ii.get("mime") != "image/jpeg" or ii.get("size", 0) > MAX_BYTES or min(ii.get("width", 0), ii.get("height", 0)) < 600:
                continue
            make, model = meta_value(ii, "Make"), meta_value(ii, "Model")
            date = str(meta_value(ii, "DateTimeOriginal") or "")
            year = int(date[:4]) if date[:4].isdigit() else None
            if not make or not year or not (2000 <= year <= 2020):
                continue
            if save(p["title"], ii, "real", "wikimedia:random-camera-photo", f"{make} {model or ''}, {date[:10]}".strip(), seen):
                got += 1
                if got >= n:
                    break
        time.sleep(1)


def category_files(cat, limit=200):
    out, cont = [], {}
    while len(out) < limit:
        d = api(action="query", list="categorymembers", cmtitle=f"Category:{cat}", cmtype="file", cmlimit=100, **cont)
        out += [m["title"] for m in d["query"]["categorymembers"]]
        if "continue" not in d:
            break
        cont = d["continue"]
    return out


def collect_ai(n):
    seen = already_have()
    have = {}
    if SOURCES.exists():
        for r in csv.DictReader(SOURCES.open()):
            if r["truth"] == "ai":
                have[r["notes"]] = have.get(r["notes"], 0) + 1
    got = sum(have.values())  # n is the total wanted, counting earlier runs
    per_cat = max(2, -(-n // len(AI_CATEGORIES)))  # ceiling division
    rng = random.Random(0)
    for cat in AI_CATEGORIES:
        took = have.get(cat.replace("Images generated by ", ""), 0)
        if took >= per_cat:
            continue
        titles = category_files(cat)
        rng.shuffle(titles)
        for i in range(0, len(titles), 20):
            if took >= per_cat or got >= n:
                break
            d = api(action="query", titles="|".join(titles[i:i + 20]), prop="imageinfo", iiprop="url|size|mime")
            for p in d["query"]["pages"]:
                ii = (p.get("imageinfo") or [{}])[0]
                if ii.get("mime") not in IMAGE_MIMES or ii.get("size", 0) > MAX_BYTES or min(ii.get("width", 0), ii.get("height", 0)) < 400:
                    continue
                if save(p["title"], ii, "ai", "wikimedia:ai-category", cat.replace("Images generated by ", ""), seen):
                    took += 1
                    got += 1
                    if took >= per_cat or got >= n:
                        break
        print(f"{cat}: {took}")
        if got >= n:
            break


if __name__ == "__main__":
    kind, n = sys.argv[1], int(sys.argv[2])
    (IMAGES / kind / "direct").mkdir(parents=True, exist_ok=True)
    {"real": collect_real, "ai": collect_ai}[kind](n)
